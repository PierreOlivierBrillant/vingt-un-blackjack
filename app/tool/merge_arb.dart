// Merges the ARB parts `app/l10n/parts/<part>.<locale>.arb` into the files
// gen-l10n reads, `app/lib/l10n/app_<locale>.arb` (GENERATED: never edit them
// by hand, edit a part and re-run this tool).
//
//   dart run tool/merge_arb.dart           (from app/) writes lib/l10n/app_fr.arb + app_en.arb
//   dart run tool/merge_arb.dart --check   exit 1 if they are not up to date
//
// `app/tool/test.ps1` runs it before `flutter gen-l10n`; a unit test
// (test/unit/merge_arb_test.dart) checks the merged files are current.
//
// Parts ([kArbParts], in output order):
//  * `core`: every string of Sprint 1 plus the shared Sprint 2 UI (tabs, game
//    selector, game table scaffold...). Its keys may NOT start with a game prefix.
//  * one part per game (`roulette`, `baccarat`, `holdem`, `craps`) and
//    `romance` (Rendez-vous): every key MUST start with one of the part's
//    prefixes followed by an upper-case letter or a digit (`rouletteSpin`,
//    `@rouletteSpin`), so two implementers can never collide.
// Rules checked (errors are listed together, nothing is written on error):
//  * each part exists in every locale and `@@locale` matches the file name;
//  * no key appears twice (in a part or across parts);
//  * `@key` metadata belongs to a message of the same part;
//  * FR/EN parity: same message keys in each part, same ICU placeholders.
import 'dart:convert';
import 'dart:io';

const kArbLocales = ['fr', 'en'];

/// Part → required key prefixes (empty for `core`).
const kArbParts = <String, List<String>>{
  'core': [],
  'roulette': ['roulette'],
  'baccarat': ['baccarat'],
  'holdem': ['holdem'],
  'craps': ['craps'],
  'romance': ['romance', 'dating'],
};

const kGeneratedNote = 'GENERATED by app/tool/merge_arb.dart from app/l10n/parts/*.arb: do not edit.';

class ArbMergeException implements Exception {
  ArbMergeException(this.errors);
  final List<String> errors;
  @override
  String toString() => 'ArbMergeException:\n  ${errors.join('\n  ')}';
}

final _messageKey = RegExp(r'^[a-z][A-Za-z0-9]*$');

bool _hasPrefix(String key, String prefix) =>
    key.length > prefix.length && key.startsWith(prefix) && RegExp(r'[A-Z0-9]').hasMatch(key[prefix.length]);

/// Top-level ICU argument names of a message (`{n}`, `{count, plural, ...}`,
/// arguments nested in plural/select branches included).
Set<String> icuArguments(String message) {
  final out = <String>{};
  var i = 0;
  void skipSpaces() {
    while (i < message.length && message[i].trim().isEmpty) {
      i++;
    }
  }

  String readWord() {
    final start = i;
    while (i < message.length && !'{},'.contains(message[i]) && message[i].trim().isNotEmpty) {
      i++;
    }
    return message.substring(start, i);
  }

  late void Function() parseArgument;

  // Text until the closing '}' of the enclosing branch (or the end).
  void parseText() {
    while (i < message.length) {
      final c = message[i];
      if (c == '}') return;
      if (c == '{') {
        i++;
        parseArgument();
      } else {
        i++;
      }
    }
  }

  parseArgument = () {
    skipSpaces();
    final name = readWord();
    if (name.isNotEmpty) out.add(name);
    skipSpaces();
    if (i < message.length && message[i] == ',') {
      i++;
      skipSpaces();
      final type = readWord();
      skipSpaces();
      if (type == 'plural' || type == 'select' || type == 'selectordinal') {
        if (i < message.length && message[i] == ',') i++;
        // Branches: selector {text} ...
        while (i < message.length) {
          skipSpaces();
          if (i >= message.length || message[i] == '}') break;
          readWord(); // =0, one, other, a select value...
          skipSpaces();
          if (i < message.length && message[i] == '{') {
            i++;
            parseText();
            if (i < message.length && message[i] == '}') i++;
          } else {
            break;
          }
        }
      } else {
        // number / date / time: skip the format up to the closing brace.
        var depth = 0;
        while (i < message.length && (message[i] != '}' || depth > 0)) {
          if (message[i] == '{') depth++;
          if (message[i] == '}') depth--;
          i++;
        }
      }
    }
    if (i < message.length && message[i] == '}') i++;
  };

  parseText();
  return out;
}

/// Merges decoded parts (`parts[part][locale]`, key order preserved) into one
/// ARB map per locale. Throws [ArbMergeException] listing every problem.
Map<String, Map<String, Object?>> mergeArbParts(Map<String, Map<String, Map<String, Object?>>> parts) {
  final errors = <String>[];
  for (final p in parts.keys) {
    if (!kArbParts.containsKey(p)) errors.add('unknown part "$p" (known: ${kArbParts.keys.join(', ')}; see tool/merge_arb.dart)');
  }
  final gamePrefixes = [for (final e in kArbParts.entries) ...e.value];
  final out = <String, Map<String, Object?>>{
    for (final loc in kArbLocales) loc: {'@@locale': loc, '@@x-generated': kGeneratedNote},
  };
  final owner = <String, Map<String, String>>{for (final loc in kArbLocales) loc: {}};

  for (final e in kArbParts.entries) {
    final part = e.key;
    final prefixes = e.value;
    final byLocale = parts[part];
    if (byLocale == null) {
      errors.add('missing part "$part" (l10n/parts/$part.<locale>.arb)');
      continue;
    }
    final messages = <String, Map<String, String>>{};
    for (final loc in kArbLocales) {
      final arb = byLocale[loc];
      final file = '$part.$loc.arb';
      if (arb == null) {
        errors.add('missing $file');
        continue;
      }
      if (arb['@@locale'] != loc) errors.add('$file: "@@locale" must be "$loc"');
      final msgs = messages[loc] = <String, String>{};
      for (final kv in arb.entries) {
        final key = kv.key;
        if (key.startsWith('@@')) continue;
        final isMeta = key.startsWith('@');
        final name = isMeta ? key.substring(1) : key;
        if (!_messageKey.hasMatch(name)) {
          errors.add('$file: invalid key "$key" (lowerCamelCase letters and digits)');
          continue;
        }
        if (prefixes.isNotEmpty && !prefixes.any((p) => _hasPrefix(name, p))) {
          errors.add('$file: key "$key" must start with ${prefixes.map((p) => '"$p"').join(' or ')} + an upper-case letter');
        }
        if (prefixes.isEmpty) {
          final p = gamePrefixes.where((p) => _hasPrefix(name, p)).firstOrNull;
          if (p != null) errors.add('$file: key "$key" uses the prefix "$p", reserved for another part');
        }
        if (isMeta) {
          if (kv.value is! Map) errors.add('$file: "$key" must be an object');
          continue;
        }
        if (kv.value is! String) {
          errors.add('$file: "$key" must be a string');
          continue;
        }
        final prev = owner[loc]![key];
        if (prev != null) {
          errors.add('$file: duplicate key "$key" (already in $prev.$loc.arb)');
          continue;
        }
        owner[loc]![key] = part;
        msgs[key] = kv.value! as String;
      }
      for (final kv in arb.entries) {
        if (kv.key.startsWith('@') && !kv.key.startsWith('@@') && !msgs.containsKey(kv.key.substring(1))) {
          errors.add('$file: metadata "${kv.key}" has no message "${kv.key.substring(1)}" in this part');
        }
      }
    }
    // FR/EN parity of this part.
    final fr = messages['fr'], en = messages['en'];
    if (fr != null && en != null) {
      for (final k in fr.keys.where((k) => !en.containsKey(k))) {
        errors.add('$part.en.arb: missing "$k" (present in $part.fr.arb)');
      }
      for (final k in en.keys.where((k) => !fr.containsKey(k))) {
        errors.add('$part.fr.arb: missing "$k" (present in $part.en.arb)');
      }
      for (final k in fr.keys.where(en.containsKey)) {
        final a = icuArguments(fr[k]!), b = icuArguments(en[k]!);
        if (a.length != b.length || !a.containsAll(b)) {
          errors.add('$part: "$k" placeholders differ (fr ${a.toList()..sort()} / en ${b.toList()..sort()})');
        }
      }
    }
    if (errors.isNotEmpty) continue;
    for (final loc in kArbLocales) {
      for (final kv in byLocale[loc]!.entries) {
        if (kv.key.startsWith('@@')) continue;
        out[loc]![kv.key] = kv.value;
      }
    }
  }
  if (errors.isNotEmpty) throw ArbMergeException(errors);
  return out;
}

/// Compact JSON for metadata (`{"placeholders": {"n": {"type": "int"}}}`).
String _compact(Object? v) {
  if (v is Map) {
    return '{${[for (final e in v.entries) '${jsonEncode(e.key.toString())}: ${_compact(e.value)}'].join(', ')}}';
  }
  if (v is List) return '[${v.map(_compact).join(', ')}]';
  return jsonEncode(v);
}

/// One entry per line, metadata compact: easy to diff and to review.
String encodeArb(Map<String, Object?> arb) {
  final b = StringBuffer('{\n');
  final entries = arb.entries.toList();
  for (var i = 0; i < entries.length; i++) {
    final e = entries[i];
    b.write('  ${jsonEncode(e.key)}: ${_compact(e.value)}');
    b.write(i == entries.length - 1 ? '\n' : ',\n');
  }
  b.write('}\n');
  return b.toString();
}

/// Reads `<appDir>/l10n/parts/*.arb`.
Map<String, Map<String, Map<String, Object?>>> readArbParts(Directory appDir) {
  final dir = Directory('${appDir.path}/l10n/parts');
  final parts = <String, Map<String, Map<String, Object?>>>{};
  final name = RegExp(r'^([a-z0-9]+)\.([a-z]{2})\.arb$');
  final errors = <String>[];
  for (final f in dir.listSync().whereType<File>()) {
    final base = f.uri.pathSegments.last;
    final m = name.firstMatch(base);
    if (m == null) {
      errors.add('unexpected file l10n/parts/$base (expected <part>.<locale>.arb)');
      continue;
    }
    try {
      final text = f.readAsStringSync();
      // jsonDecode silently keeps the last of two equal keys: look for them in the text
      // (one top-level entry per line, as in every part).
      final seen = <String>{};
      for (final m in RegExp(r'^\s*"([^"]+)"\s*:', multiLine: true).allMatches(text)) {
        if (!seen.add(m.group(1)!)) errors.add('l10n/parts/$base: duplicate key "${m.group(1)}"');
      }
      final decoded = jsonDecode(text);
      if (decoded is! Map) throw const FormatException('not an object');
      (parts[m.group(1)!] ??= {})[m.group(2)!] = decoded.cast<String, Object?>();
    } on FormatException catch (e) {
      errors.add('l10n/parts/$base: invalid JSON (${e.message})');
    }
  }
  if (errors.isNotEmpty) throw ArbMergeException(errors);
  return parts;
}

/// The generated files' expected contents (`lib/l10n/app_<locale>.arb`).
Map<String, String> mergedArbFiles(Directory appDir) {
  final merged = mergeArbParts(readArbParts(appDir));
  return {for (final loc in kArbLocales) '${appDir.path}/lib/l10n/app_$loc.arb': encodeArb(merged[loc]!)};
}

void main(List<String> args) {
  final check = args.contains('--check');
  final app = Directory.current;
  try {
    final files = mergedArbFiles(app);
    var stale = 0;
    for (final e in files.entries) {
      final f = File(e.key);
      final current = f.existsSync() ? f.readAsStringSync().replaceAll('\r\n', '\n') : null;
      if (current == e.value) continue;
      stale++;
      if (check) {
        stderr.writeln('out of date: ${e.key} (run: dart run tool/merge_arb.dart)');
      } else {
        f.writeAsStringSync(e.value);
        stdout.writeln('wrote ${e.key}');
      }
    }
    if (stale == 0) stdout.writeln('ARB files up to date (${kArbParts.length} parts × ${kArbLocales.length} locales).');
    if (check && stale > 0) exitCode = 1;
  } on ArbMergeException catch (e) {
    stderr.writeln('ARB merge failed:');
    for (final err in e.errors) {
      stderr.writeln('  - $err');
    }
    exitCode = 1;
  }
}
