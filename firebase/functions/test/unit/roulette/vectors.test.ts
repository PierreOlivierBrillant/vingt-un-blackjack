/**
 * Fairness and rules vectors shared with the Dart client: app/assets/fairness/roulette_vectors.json
 * (committed). The Dart tests (app/test/unit/roulette/roulette_vectors_test.dart) recompute every
 * value: seed → commitment → number (`seededRng(seed).nextInt(37)`), the wheel, the spot grammar,
 * the payouts, the limits and the call bets. Regenerate after an intended change with
 * `npx vitest run --config vitest.unit.config.mts test/unit/roulette/vectors.test.ts -u`.
 */
import { describe, expect, it } from 'vitest';
import { fastRng, seededRng, sha256Hex } from '../../../src/engine';
import { ANNOUNCE_IDS, announceBoard, RED_NUMBERS, rouletteLimits, settleBoard, SPOTS, WHEEL_ORDER, wheelNeighbours } from '../../../src/games/roulette/engine';
import type { BetMap } from '../../../src/shared/games/common';
import { ROULETTE_PAYOUTS } from '../../../src/shared/games/roulette';

function vectors() {
  const seeds = [
    ...Array.from({ length: 48 }, (_, i) => sha256Hex(`roulette-vector-${i}`)),
    'a', 'seed', 'Rien ne va plus', '0'.repeat(64), 'f'.repeat(64),
  ];
  const draws = seeds.map((seed) => ({ seed, commit: sha256Hex(seed), number: seededRng(seed).nextInt(37) }));
  // a few seeds whose DRBG stream needs a second block or rejects a word are covered by the 48 above;
  // also check several successive draws of one stream (the client reuses SeededRng)
  const stream = seededRng('roulette-stream');
  const streamDraws = Array.from({ length: 40 }, () => stream.nextInt(37));
  const rng = fastRng(37);
  const ids = [...SPOTS.keys()];
  const settlements = Array.from({ length: 30 }, (_, i) => {
    const board: BetMap = {};
    const k = 1 + rng.nextInt(6);
    for (let j = 0; j < k; j++) board[ids[rng.nextInt(ids.length)]] = 100 * (1 + rng.nextInt(20));
    if (i % 5 === 0) board.red = 300;
    const n = i % 7 === 0 ? 0 : rng.nextInt(37);
    const shield = i % 3 === 0;
    const o = settleBoard(board, n, shield);
    return { board, number: n, shield, returnCents: o.returnCents, wins: o.wins };
  });
  return {
    note: 'GENERATED by firebase/functions/test/unit/roulette/vectors.test.ts — do not edit.',
    draws,
    stream: { seed: 'roulette-stream', numbers: streamDraws },
    wheelOrder: WHEEL_ORDER,
    red: RED_NUMBERS,
    payouts: ROULETTE_PAYOUTS,
    spots: Object.fromEntries([...SPOTS.values()].map((s) => [s.id, { type: s.type, numbers: s.numbers }])),
    limits: { low: rouletteLimits('low'), mid: rouletteLimits('mid'), high: rouletteLimits('high') },
    announces: Object.fromEntries(ANNOUNCE_IDS.map((id) => [id, announceBoard(id, 1)])),
    neighbours: Object.fromEntries(WHEEL_ORDER.map((n) => [String(n), wheelNeighbours(n, 2)])),
    settlements,
  };
}

describe('roulette vectors shared with Dart', () => {
  it('match app/assets/fairness/roulette_vectors.json', async () => {
    const v = vectors();
    expect(new Set(v.draws.map((d) => d.number)).size).toBeGreaterThan(20);
    await expect(JSON.stringify(v, null, 1) + '\n').toMatchFileSnapshot('../../../../../app/assets/fairness/roulette_vectors.json');
  });
});
