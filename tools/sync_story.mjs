#!/usr/bin/env node
// Copie l'histoire de Rendez-vous (source unique : firebase/functions/src/romance/story/*.json) vers l'app :
//  - app/assets/story/<fichier>.json (copie à l'identique, fins de ligne normalisées en LF) ;
//  - app/lib/features/romance/story/story_bundle.g.dart : les mêmes textes embarqués dans le code Dart
//    (lecture synchrone, sans dépendre de la déclaration des assets dans pubspec.yaml) + leur SHA-256.
//
//   node tools/sync_story.mjs           écrit les copies
//   node tools/sync_story.mjs --check   code 1 si les copies ne sont pas à jour (rien n'est écrit)
//
// Les SHA-256 sont calculés sur le contenu en LF (le dépôt est extrait en CRLF sous Windows) ; les tests de
// parité (firebase/functions/test/unit/romance/parity.test.ts, app/test/unit/romance_story_test.dart) font de même.
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'firebase/functions/src/romance/story');
const ASSETS = path.join(ROOT, 'app/assets/story');
const BUNDLE = path.join(ROOT, 'app/lib/features/romance/story/story_bundle.g.dart');

const lf = (s) => s.replace(/\r\n/g, '\n');
const sha256 = (s) => createHash('sha256').update(Buffer.from(s, 'utf8')).digest('hex');
/** Dart string literal: JSON string escapes are valid Dart escapes; `$` must be escaped too. */
const dartString = (s) => JSON.stringify(s).replace(/\$/g, '\\$');

function build() {
  const names = fs.readdirSync(SRC).filter((f) => f.endsWith('.json')).sort();
  const files = names.map((name) => {
    const text = lf(fs.readFileSync(path.join(SRC, name), 'utf8'));
    JSON.parse(text); // fails loudly on a broken file
    return { name, text, sha: sha256(text) };
  });
  const dart = [
    '// GENERATED by tools/sync_story.mjs from firebase/functions/src/romance/story/*.json: do not edit.',
    '// Story of Rendez-vous embedded in the app (same bytes as app/assets/story/, LF line endings).',
    '// ignore_for_file: lines_longer_than_80_chars',
    'library;',
    '',
    '/// File name → JSON text.',
    'const kStoryFiles = <String, String>{',
    ...files.map((f) => `  '${f.name}': ${dartString(f.text)},`),
    '};',
    '',
    '/// File name → SHA-256 (hex) of its UTF-8 text.',
    'const kStorySha256 = <String, String>{',
    ...files.map((f) => `  '${f.name}': '${f.sha}',`),
    '};',
    '',
  ].join('\n');
  return { files, dart };
}

function main() {
  const check = process.argv.includes('--check');
  const { files, dart } = build();
  const stale = [];
  const existing = fs.existsSync(ASSETS) ? fs.readdirSync(ASSETS).filter((f) => f.endsWith('.json')) : [];
  for (const f of existing) if (!files.some((x) => x.name === f)) stale.push(`app/assets/story/${f} (obsolète)`);
  for (const f of files) {
    const target = path.join(ASSETS, f.name);
    if (!fs.existsSync(target) || lf(fs.readFileSync(target, 'utf8')) !== f.text) stale.push(`app/assets/story/${f.name}`);
  }
  if (!fs.existsSync(BUNDLE) || lf(fs.readFileSync(BUNDLE, 'utf8')) !== dart) stale.push(path.relative(ROOT, BUNDLE).replace(/\\/g, '/'));
  if (check) {
    if (stale.length) {
      console.error(`Histoire non synchronisée (lancer node tools/sync_story.mjs) :\n  ${stale.join('\n  ')}`);
      process.exit(1);
    }
    console.log(`Histoire synchronisée (${files.length} fichiers).`);
    return;
  }
  fs.mkdirSync(ASSETS, { recursive: true });
  fs.mkdirSync(path.dirname(BUNDLE), { recursive: true });
  for (const f of existing) if (!files.some((x) => x.name === f)) fs.rmSync(path.join(ASSETS, f));
  for (const f of files) fs.writeFileSync(path.join(ASSETS, f.name), f.text);
  fs.writeFileSync(BUNDLE, dart);
  console.log(`${files.length} fichiers copiés vers app/assets/story/ et ${path.relative(ROOT, BUNDLE)}.`);
}

main();
